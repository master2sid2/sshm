package sshconfig

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"github.com/master2sid2/sshm/internal/config"
)

// GeneratedHeader starts every file written by Render. Export refuses to
// overwrite a file that does not begin with it, so a hand-written config
// that happens to sit at the same path is never clobbered.
const GeneratedHeader = "# Generated by sshm"

// ExportEntry is one profile to write, with the folder path it lives in
// (root first) for the comment above it and for disambiguating aliases.
type ExportEntry struct {
	Profile config.Profile
	Folders []string
}

// Render writes entries as an ssh_config fragment. Passwords and key
// passphrases are never written; key-based profiles get IdentityFile (and
// IdentitiesOnly, so ssh does not try every agent key first). Aliases are
// made unique: a name used twice gets its folder path prepended, and a
// numeric suffix as the last resort.
func Render(entries []ExportEntry, version string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s %s — do not edit: \"sshm export-ssh\" overwrites this file.\n", GeneratedHeader, version)
	b.WriteString("# Passwords and key passphrases stay in the sshm vault and are not exported.\n")

	names := aliases(entries)
	for i, e := range entries {
		p := e.Profile
		b.WriteString("\n")
		if len(e.Folders) > 0 {
			fmt.Fprintf(&b, "# %s / %s\n", strings.Join(e.Folders, " / "), p.Name)
		} else if alias := Alias(p.Name); alias != p.Name {
			fmt.Fprintf(&b, "# %s\n", p.Name)
		}
		fmt.Fprintf(&b, "Host %s\n", names[i])
		fmt.Fprintf(&b, "    HostName %s\n", quote(p.Host))
		if p.User != "" {
			fmt.Fprintf(&b, "    User %s\n", quote(p.User))
		}
		if p.Port != 0 && p.Port != 22 {
			fmt.Fprintf(&b, "    Port %d\n", p.Port)
		}
		switch p.AuthType {
		case config.AuthKey:
			if p.KeyPath != "" {
				fmt.Fprintf(&b, "    IdentityFile %s\n", quote(p.KeyPath))
				b.WriteString("    IdentitiesOnly yes\n")
			}
		case config.AuthPassword:
			b.WriteString("    # password authentication: ssh will ask for the password\n")
			b.WriteString("    PreferredAuthentications keyboard-interactive,password\n")
		}
		for _, t := range p.Tunnels {
			kw := "LocalForward"
			bind, target := hostPort(t.LocalHost, t.LocalPort), hostPort(t.RemoteHost, t.RemotePort)
			if t.Direction == config.TunnelRemote {
				kw = "RemoteForward"
				bind, target = hostPort(t.RemoteHost, t.RemotePort), hostPort(t.LocalHost, t.LocalPort)
			}
			fmt.Fprintf(&b, "    %s %s %s\n", kw, bind, target)
		}
	}
	return b.Bytes()
}

// aliases returns the Host alias for each entry, unique across entries.
func aliases(entries []ExportEntry) []string {
	count := map[string]int{}
	for _, e := range entries {
		count[Alias(e.Profile.Name)]++
	}
	out := make([]string, len(entries))
	used := map[string]bool{}
	for i, e := range entries {
		a := Alias(e.Profile.Name)
		if count[a] > 1 && len(e.Folders) > 0 {
			a = Alias(strings.Join(e.Folders, "-") + "-" + e.Profile.Name)
		}
		base := a
		for n := 2; used[a]; n++ {
			a = base + "-" + strconv.Itoa(n)
		}
		used[a] = true
		out[i] = a
	}
	return out
}

// Alias turns a profile name into a Host alias: no whitespace (a separator
// in ssh_config), no pattern characters (* ? !), and no quotes or commas.
func Alias(name string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.TrimSpace(name) {
		ok := unicode.IsLetter(r) || unicode.IsDigit(r) || strings.ContainsRune("._@+:", r)
		if !ok { // includes '-': runs of separators collapse into one dash
			if !dash && b.Len() > 0 {
				b.WriteByte('-')
				dash = true
			}
			continue
		}
		b.WriteRune(r)
		dash = false
	}
	a := strings.Trim(b.String(), "-")
	if a == "" {
		return "host"
	}
	return a
}

// hostPort renders a forward endpoint; IPv6 addresses need brackets.
func hostPort(host string, port int) string {
	if host == "" {
		return strconv.Itoa(port)
	}
	if strings.Contains(host, ":") {
		return "[" + host + "]:" + strconv.Itoa(port)
	}
	return host + ":" + strconv.Itoa(port)
}

func quote(s string) string {
	if strings.ContainsAny(s, " \t\"#") {
		return `"` + strings.ReplaceAll(s, `"`, ``) + `"`
	}
	return s
}

// IncludeLine is what export adds to ~/.ssh/config so ssh reads the file.
const IncludeLine = "Include config.d/sshm.conf"

// Includes reports whether the ssh config at configPath already reads file,
// directly or through a glob such as config.d/*.
func Includes(configPath, sshDir, file string) (bool, error) {
	c, err := Load(configPath, sshDir)
	if err != nil {
		return false, err
	}
	want, err := filepath.Abs(file)
	if err != nil {
		return false, err
	}
	for _, f := range c.Files {
		if abs, err := filepath.Abs(f); err == nil && abs == want {
			return true, nil
		}
	}
	return false, nil
}

// PrependInclude returns content with an Include line for sshm's file
// added at the top. It must be first: an Include after a Host line would
// only apply inside that Host block.
func PrependInclude(content []byte) []byte {
	var b bytes.Buffer
	b.WriteString("# Added by sshm: hosts exported with \"sshm export-ssh\".\n")
	b.WriteString(IncludeLine + "\n\n")
	b.Write(content)
	return b.Bytes()
}

// FileExists reports whether path exists (any error but "not exist" counts
// as existing, so callers do not overwrite what they could not inspect).
func FileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil || !os.IsNotExist(err)
}
