func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestImportSSHFoldersDuplicatesAndOwnExport(t *testing.T) {
	sshDir := t.TempDir()
	cfg := filepath.Join(sshDir, "config")
	own := filepath.Join(sshDir, "config.d", "sshm.conf")
	key := filepath.Join(sshDir, "id_test")
	write(t, key, "not really a key")
	write(t, cfg, "Include config.d/*\n\nHost web\n  HostName 10.0.0.1\n  User deploy\n  IdentityFile "+key+"\n\nHost nokey\n  HostName 10.0.0.2\n  IdentityFile ~/.ssh/definitely-missing\n  ProxyJump bastion\n")
	write(t, filepath.Join(sshDir, "config.d", "work.conf"), "Host work\n  HostName work.lan\n  Port 2200\n")
	write(t, own, "# Generated by sshm\nHost exported\n  HostName 10.9.9.9\n")

	store, err := config.Open(filepath.Join(t.TempDir(), "vault.enc"), []byte("pw"))
	if err != nil {
		t.Fatal(err)
	}

	rep, err := importSSH(store, cfg, sshDir, own, true)
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.added) != 3 || len(store.Profiles()) != 0 {
		t.Fatalf("dry run: added=%v, vault has %d", rep.added, len(store.Profiles()))
	}

	rep, err = importSSH(store, cfg, sshDir, own, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.added) != 3 {
		t.Fatalf("added = %v", rep.added)
	}
	if len(rep.warnings) != 2 {
		t.Errorf("want a missing-key and a ProxyJump warning, got %v", rep.warnings)
	}

	roots := store.GroupsInGroup("")
	if len(roots) != 2 || roots[0].Name != "ssh config" || roots[1].Name != "work" {
		t.Fatalf("folders = %+v", roots)
	}
	web := store.ProfilesInGroup(roots[0].ID)
	if len(web) != 2 {
		t.Fatalf("ssh config folder has %d hosts", len(web))
	}
	for _, p := range web {
		switch p.Name {
		case "web":
			if p.AuthType != config.AuthKey || p.KeyPath != key || p.User != "deploy" || p.Password != "" {
				t.Errorf("web = %+v", p)
			}
		case "nokey":
			if p.AuthType != config.AuthAgent || p.KeyPath != "" {
				t.Errorf("a missing IdentityFile must fall back to the agent: %+v", p)
			}
		}
	}
	if w := store.ProfilesInGroup(roots[1].ID); len(w) != 1 || w[0].Port != 2200 {
		t.Errorf("work = %+v", w)
	}

	// Importing again adds nothing.
	rep, err = importSSH(store, cfg, sshDir, own, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.added) != 0 || len(rep.skipped) != 3 || len(store.GroupsInGroup("")) != 2 {
		t.Errorf("re-import: added=%v skipped=%v", rep.added, rep.skipped)
	}
}

func TestImportDoesNotUseALockedFolder(t *testing.T) {
	sshDir := t.TempDir()
	cfg := filepath.Join(sshDir, "config")
	write(t, cfg, "Host a\n  HostName 10.0.0.1\n")
	store, err := config.Open(filepath.Join(t.TempDir(), "vault.enc"), []byte("pw"))
	if err != nil {
		t.Fatal(err)
	}
	g := config.NewGroup("")
	g.Name = "ssh config"
	if err := store.AddGroup(g); err != nil {
		t.Fatal(err)
	}
	if err := store.SetGroupPassword(g.ID, "x"); err != nil {
		t.Fatal(err)
	}
	if _, err := importSSH(store, cfg, sshDir, filepath.Join(sshDir, "none"), false); err != nil {
		t.Fatal(err)
	}
	if len(store.ProfilesInGroup(g.ID)) != 0 {
		t.Fatal("imported hosts must not land in a locked folder")
	}
}

func TestExportSkipsLockedAndWritesInclude(t *testing.T) {
	store, err := config.Open(filepath.Join(t.TempDir(), "vault.enc"), []byte("pw"))
	if err != nil {
		t.Fatal(err)
	}
	open, closed := config.NewGroup(""), config.NewGroup("")
	open.Name, closed.Name = "prod", "secret"
	sub := config.NewGroup(closed.ID)
	sub.Name = "inner"
	for _, g := range []config.Group{open, closed, sub} {
		if err := store.AddGroup(g); err != nil {
			t.Fatal(err)
		}
	}
	if err := store.SetGroupPassword(closed.ID, "x"); err != nil {
		t.Fatal(err)
	}
	for i, gid := range []string{open.ID, sub.ID, ""} {
		p := config.NewProfile()
		p.Name, p.Host, p.GroupID = "h"+string(rune('0'+i)), "10.0.0.1", gid
		p.AuthType, p.Password = config.AuthPassword, "PW"
		if err := store.Add(p); err != nil {
			t.Fatal(err)
		}
	}

	entries, skipped, err := exportEntries(store, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 2 || skipped != 1 {
		t.Fatalf("entries=%d skipped=%d", len(entries), skipped)
	}
	if entries[0].Profile.Name != "h2" || entries[1].Folders[0] != "prod" {
		t.Errorf("order: %+v", entries)
	}

	sshDir := t.TempDir()
	cfg := filepath.Join(sshDir, "config")
	out := filepath.Join(sshDir, "config.d", "sshm.conf")
	original := "Host mine\n  User me\n"
	write(t, cfg, original)

	data := sshconfig.Render(entries, "test")
	if strings.Contains(string(data), "PW") {
		t.Fatal("password exported")
	}
	if err := writeExport(out, data); err != nil {
		t.Fatal(err)
	}
	if err := ensureInclude(cfg, sshDir, out, true); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(cfg)
	if !strings.HasPrefix(strings.SplitN(string(got), "\n", 3)[1], sshconfig.IncludeLine) || !strings.HasSuffix(string(got), original) {
		t.Errorf("config after include:\n%s", got)
	}
	if bak, _ := os.ReadFile(cfg + ".bak"); string(bak) != original {
		t.Errorf("backup = %q", bak)
	}
	// Second time: already included, file untouched.
	if err := ensureInclude(cfg, sshDir, out, true); err != nil {
		t.Fatal(err)
	}
	if again, _ := os.ReadFile(cfg); string(again) != string(got) {
		t.Error("the Include line must be added only once")
	}

	// A hand-written file at the export path is not overwritten without
	// confirmation (stdin here is not a terminal and answers nothing).
	write(t, out, "Host handwritten\n")
	withStdin(t, "", func() {
		if err := writeExport(out, data); err == nil {
			t.Error("must refuse to overwrite a file sshm did not generate")
		}
	})
}

// With "Include config.d/*" at the top, sshm's own export is read before
// the user's Host blocks. It must not hide them from a later import.
func TestReimportWithExportIncludedFirst(t *testing.T) {
	sshDir := t.TempDir()
	cfg := filepath.Join(sshDir, "config")
	own := filepath.Join(sshDir, "config.d", "sshm.conf")
	write(t, cfg, "Include config.d/*\nHost web\n  HostName 10.0.0.1\n  User deploy\n")
	write(t, own, "# Generated by sshm\nHost web\n  HostName 10.9.9.9\n  User other\n")

	hosts, err := sshHosts(cfg, sshDir, own)
	if err != nil {
		t.Fatal(err)
	}
	if len(hosts) != 1 || hosts[0].HostName != "10.0.0.1" || hosts[0].User != "deploy" {
		t.Fatalf("hosts = %+v", hosts)
	}

	p := config.NewProfile()
	p.Name, p.Host, p.User = "web", "10.0.0.1", "deploy"
	q := config.NewProfile()
	q.Name, q.Host, q.User = "new", "10.0.0.2", "deploy"
	left, dups := withoutKnown([]sshconfig.ExportEntry{{Profile: p}, {Profile: q}}, hosts)
	if dups != 1 || len(left) != 1 || left[0].Profile.Name != "new" {
		t.Errorf("withoutKnown: left=%+v dups=%d", left, dups)
	}
}
